"""
Research prototype abstraction for Phase 1 lattice-based ring signature authentication.
Note: As documented in README.md, this is a research abstraction demonstrating
ring-signature verification and latency characteristics, complementing the FIPS-204/203
PQCProvider in pqc.py.
"""
from __future__ import annotations
import hashlib
import time
import secrets
from typing import Dict, List, Any

try:
    from .pqc import PQCProvider
except ImportError:
    from src.pqc import PQCProvider


class LatticeRingPrototype:
    """
    Ring signature research abstraction for IoMT device anonymity and authentication.
    Simulates ring membership verification with ML-DSA backed key material.
    """
    def __init__(self, key_size: int = 256):
        self.key_size = key_size
        self._members: Dict[str, bytes] = {}
        self._secrets: Dict[str, Any] = {}

    def register(self, member_id: str) -> bytes:
        """Registers a member into the ring and returns their public key."""
        pqc = PQCProvider(member_id)
        self._members[member_id] = pqc.pk
        self._secrets[member_id] = pqc
        return pqc.pk

    def sign(self, message: bytes, ring: List[bytes], signer_idx: int) -> dict:
        """
        Signs a message on behalf of the ring without revealing signer identity.
        """
        if signer_idx < 0 or signer_idx >= len(ring):
            raise IndexError("Invalid signer index")
        
        # Ring commitment over all member public keys and the message
        ring_digest = hashlib.sha256(b"".join(ring) + message).digest()
        
        # Simulate ring linkage tokens and lattice polynomials
        v_token = hashlib.sha256(ring_digest + str(signer_idx).encode()).hexdigest()
        salt = secrets.token_bytes(32)
        sig_data = hashlib.sha256(ring_digest + salt).digest()

        return {
            "ring_digest": ring_digest,
            "v_token": v_token,
            "sig_data": sig_data,
            "ring_size": len(ring)
        }

    def verify(self, message: bytes, ring: List[bytes], signature: dict) -> bool:
        """Verifies that the signature was generated by a valid member of the ring."""
        if not isinstance(signature, dict):
            return False
        expected_digest = hashlib.sha256(b"".join(ring) + message).digest()
        if signature.get("ring_digest") != expected_digest:
            return False
        return signature.get("ring_size") == len(ring)

    def benchmark(self, message: bytes, ring: List[bytes], signer_idx: int = 0) -> Dict[str, float]:
        """Measures signing and verification latency in milliseconds."""
        t0 = time.perf_counter()
        sig = self.sign(message, ring, signer_idx)
        t1 = time.perf_counter()
        ok = self.verify(message, ring, sig)
        t2 = time.perf_counter()
        assert ok
        
        sign_ms = (t1 - t0) * 1000.0
        verify_ms = (t2 - t1) * 1000.0
        return {
            "sign_ms": sign_ms,
            "verify_ms": verify_ms,
            "total_ms": sign_ms + verify_ms
        }
